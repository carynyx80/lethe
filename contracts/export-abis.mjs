// Writes typed ABIs from Foundry build output into packages/shared/src/abi.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = (name) => JSON.parse(readFileSync(join(here, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;
const body = ["LetheAuction", "TestToken"]
  .map((n) => `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(out(n), null, 2)} as const;\n`)
  .join("\n");
writeFileSync(
  join(here, "..", "packages", "shared", "src", "abi.ts"),
  `// Generated by contracts/export-abis.mjs from Foundry output. Do not edit.\n\n${body}`,
);
console.log("wrote packages/shared/src/abi.ts");
